/**
 * 按题目上下文构造注入片段
 *
 * @param {object} problem - algo_problems.json 里的一条
 * @returns {string} 注入到 user 消息前的上下文，控制在 200 token 内
 */
function buildProblemContext(problem) {
  if (!problem || !problem.id) return '';

  const parts = [];
  parts.push(`当前题目：${problem.titleCn || problem.title}（${problem.source} ${problem.pid || ''}，难度 ${problem.rating || '未知'}）`);

  const hints = (problem.tags || [])
    .map(k => TAG_HINTS[k])
    .filter(Boolean)
    .slice(0, 2);

  if (hints.length) {
    parts.push('该知识点训练要点：');
    hints.forEach((h, i) => {
      parts.push(`${i + 1}) 练什么：${h[0]}`);
      parts.push(`   常见卡点：${h[1]}`);
      parts.push(`   判定真会：${h[2]}`);
    });
  }

  // 难度带诊断：判断这题对学生是否合适
  if (problem.band) {
    const bandMap = {
      entry: '入门。如果学生觉得难，说明基础语法或读题有问题，不是算法问题。',
      basic: '基础。这是训练量的主战场，速度比难度重要。',
      improve: '提高。多数校赛/省赛的分水岭在这一档。',
      advanced: '进阶。做到这一档才开始需要系统地补知识点。',
      challenge: '挑战。做不出来是正常的，看了题解也不算失败。'
    };
    if (bandMap[problem.band]) parts.push(`难度定位：${bandMap[problem.band]}`);
  }

  return parts.join('\n');
}

