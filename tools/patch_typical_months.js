const seed = JSON.parse(fs.readFileSync(FILE, 'utf-8'));
let hit = 0;
for (const item of seed) {
  const months = item.level === 'A' ? MONTHS[item.serialNo] : MONTHS['B' + item.serialNo];
  if (months && months.length) {
    item.typicalMonths = [...months].sort((a, b) => a - b);
    hit++;
  } else {
    item.typicalMonths = null;
  }
}
fs.writeFileSync(FILE, JSON.stringify(seed, null, 2) + '\n', 'utf-8');
console.log(`seed total=${seed.length}, typicalMonths filled=${hit}`);
