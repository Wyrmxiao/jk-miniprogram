# 与计算机学院专业培养最相关的赛事，首页重点推荐
CS_HOSTS = ("计算机学院", "大数据学院", "信息安全学院")


def build(items, level):
    out = []
    for idx, (name, host, category, directions) in enumerate(items, start=1):
        out.append({
            "serialNo": idx,
            "name": name,
            "level": level,
            "category": category,
            "host": host,
            "directions": directions,
            "isFocus": host in CS_HOSTS,
            "regStart": None,
            "regEnd": None,
            "contestDate": None,
            "officialUrl": "",
            "intro": "",
            "status": "published",
            "source": "移通〔2026〕83号 附件" + ("1" if level == "A" else "2"),
            "deleted": False,
        })
    return out


